# Paints the ASCII map sources (maps/*.txt) from rectangle operations, so the
# layouts can be reasoned about in coordinates (1 char = 2 m). Edit here, run
#   python3 maps/paint.py && python3 ascii_plan.py maps/<name>.txt
import os
HERE = os.path.dirname(os.path.abspath(__file__))

class Canvas:
    def __init__(s, w, h): s.w, s.h = w, h; s.g = [["#"] * w for _ in range(h)]
    def r(s, x0, y0, x1, y1, c):
        for y in range(max(0, y0), min(s.h, y1)):
            for x in range(max(0, x0), min(s.w, x1)): s.g[y][x] = c
        return s
    def p(s, *pts, c="p"):
        for x, y in pts: s.g[y][x] = c
        return s
    def save(s, name, theme, mode):
        txt = "name: %s\ntheme: %s\nmode: %s\n---\n" % (name, theme, mode) + "\n".join("".join(r) for r in s.g) + "\n"
        open(os.path.join(HERE, name + ".txt"), "w").write(txt)
        print(txt)

